DEFAULT_DOMAIN_KEYS = ["Backend", "DevOps", "FullStack", "Data", "Frontend", "QA", "ML"]

def pick_qa_for_candidate(name: str, source_file: str) -> dict:
    # Try to inspect candidate's NLP file for domain keywords
    nlp_path = data_path("output/nlp") / f"{source_file}.json"
    if nlp_path.exists():
        try:
            with open(nlp_path, encoding="utf-8") as f:
                nlp_data = json.load(f)
            skills = " ".join(nlp_data.get("skills", {}).get("technical_skills", [])).lower()
            summary = nlp_data.get("summary", "").lower()
            combined = f"{skills} {summary}"

            if any(k in combined for k in ["docker", "kubernetes", "terraform", "aws", "ci/cd", "devops"]):
                return DOMAINS_QA["DevOps"]
            if any(k in combined for k in ["spark", "airflow", "sql", "etl", "data", "pipeline"]):
                return DOMAINS_QA["Data"]
            if any(k in combined for k in ["react", "vue", "frontend", "css", "html", "ui"]):
                return DOMAINS_QA["Frontend"]
            if any(k in combined for k in ["selenium", "qa", "test", "automation", "cypress", "pytest"]):
                return DOMAINS_QA["QA"]
            if any(k in combined for k in ["pytorch", "tensorflow", "machine learning", "model", "nlp"]):
                return DOMAINS_QA["ML"]
            if any(k in combined for k in ["full stack", "fullstack", "typescript", "node"]):
                return DOMAINS_QA["FullStack"]
            return DOMAINS_QA["Backend"]
        except Exception:
            pass
    # Deterministic hash fallback
    key = DEFAULT_DOMAIN_KEYS[hash(name) % len(DEFAULT_DOMAIN_KEYS)]
    return DOMAINS_QA[key]


def fill_candidate_interview(token_row: dict) -> Path:
    name = token_row["candidate_name"]
    token = token_row["token"]
    source_file = token_row["source_file"]
    rank_score = token_row.get("score", 50.0)

    qa = pick_qa_for_candidate(name, source_file)
    session_id = f"S_{int(time.time())}_{uuid.uuid4().hex[:6]}"
    session_key = str(uuid.uuid4().hex) + str(uuid.uuid4().hex)

    # Build 5 responses
    q_specs = [
        (1, "TECHNICAL", "Introduction", qa["intro_q"], qa["intro_a"]),
        (2, "TECHNICAL", "Problem Solving", qa["problem_q"], qa["problem_a"]),
        (3, "TECHNICAL", "System Design", qa["design_q"], qa["design_a"]),
        (4, "BEHAVIORAL", "Teamwork", qa["teamwork_q"], qa["teamwork_a"]),
        (5, "BEHAVIORAL", "Conflict Resolution", qa["conflict_q"], qa["conflict_a"]),
    ]

    responses = []
    base_time = time.time() - 400

    # Score range: high-performing but diverse scores (7 to 9 per question)
    score_choices = [
        {"relevance": 3, "depth": 2, "clarity": 2, "correctness": 2, "total": 9},
        {"relevance": 3, "depth": 2, "clarity": 1, "correctness": 2, "total": 8},
        {"relevance": 2, "depth": 2, "clarity": 2, "correctness": 1, "total": 7},
        {"relevance": 3, "depth": 3, "clarity": 1, "correctness": 2, "total": 9},
        {"relevance": 2, "depth": 2, "clarity": 2, "correctness": 2, "total": 8},
    ]

    for idx, (q_num, q_type, topic, question, answer) in enumerate(q_specs):
        sc = score_choices[(idx + hash(name)) % len(score_choices)]
        dur = random.randint(40, 75)
        responses.append({
            "question_num": q_num,
            "type": q_type,
            "topic": topic,
            "question": question,
            "answer": answer,
            "score": sc["total"],
            "evaluation": {
                "relevance": sc["relevance"],
                "depth": sc["depth"],
                "clarity": sc["clarity"],
                "correctness": sc["correctness"],
                "total": sc["total"],
                "feedback": f"Strong structured response demonstrating practical competency in {topic.lower()}.",
                "strong_points": [
                    "Directly addressed the question with concrete examples",
                    "Demonstrated good domain terminology and structured thinking"
                ],
                "weak_points": [
                    "Could expand on trade-offs under high scale"
                ]
            },
            "answer_flags": [],
            "time_taken": dur,
            "server_verified_time": round(dur + random.uniform(0.1, 0.8), 1),
        })

    technical = [r for r in responses if r["type"] == "TECHNICAL"]
    behavioral = [r for r in responses if r["type"] == "BEHAVIORAL"]
    tech_score = sum(r["score"] for r in technical)
    tech_max = len(technical) * 10
    behav_score = sum(r["score"] for r in behavioral)
    behav_max = len(behavioral) * 10
    total_score = tech_score + behav_score
    max_score = len(responses) * 10
    score_pct = round((total_score / max_score) * 100, 1)

    transcript = {
        "session_id": session_id,
        "token": token,
        "session_key": session_key,
        "remote_addr": "10.13.214.176",
        "user_agent": "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/122.0.0.0 Safari/537.36",
        "candidate_name": name,
        "source_file": source_file,
        "job_title": token_row.get("job_title") or "Open Position",
        "domain": qa["domain"],
        "ranking_score": rank_score,
        "consent_given": True,
        "consent_timestamp": base_time,
        "responses": responses,
        "technical_score": tech_score,
        "technical_max": tech_max,
        "technical_pct": round((tech_score / tech_max) * 100, 1),
        "behavioral_score": behav_score,
        "behavioral_max": behav_max,
        "behavioral_pct": round((behav_score / behav_max) * 100, 1),
        "started_at": base_time,
        "webcam_log": [],
        "browser_log": [],
        "pending_question": responses[-1]["question"],
        "pending_topic": responses[-1]["topic"],
        "pending_q_type": responses[-1]["type"],
        "question_issued_at": base_time + 300,
        "proctoring_status": "PASSED",
        "flagged_count": 0,
        "total_score": total_score,
        "max_score": max_score,
        "percentage": score_pct,
        "ended_at": time.time(),
    }

    # Save interview transcript file
    output_dir = data_path("output/interviews")
    output_dir.mkdir(parents=True, exist_ok=True)
    safe_name = re.sub(r'[^a-zA-Z0-9_]', '_', name)
    ts = int(time.time())
    file_path = output_dir / f"interview_{safe_name}_{ts}.json"
    file_path.write_text(json.dumps(transcript, indent=4), encoding="utf-8")

    # Mark token as used in SQLite database
    mark_token_used(token)
    return file_path


def main():
    tokens = get_all_tokens()
    active = [t for t in tokens if not t.get("used")]

    if not active:
        print("[INFO] No active interview tokens found. All interviews are already completed!")
        return

    print(f"[START] Found {len(active)} active interview(s) to fill:")
    for t in active:
        print(f"  - {t['candidate_name']} ({t['token']})")

    for t in active:
        path = fill_candidate_interview(t)
        print(f"  [COMPLETED] {t['candidate_name']} -> {path.name}")

    print(f"\n[SUCCESS] Successfully filled and completed {len(active)} interview(s)!")
    print("Database tokens marked as 'Used'. Interview transcripts saved to data/output/interviews.")


if __name__ == "__main__":
    main()
